#[test]
fn queue_overflow_closes_only_that_connection_without_blocking_publication() {
    let (slow, mut slow_receiver) = ConnectionOutput::new(1, 0, None).unwrap();
    let (fast, mut fast_receiver) = ConnectionOutput::new(4, 0, None).unwrap();
    slow.finish_sync(|_| unreachable!()).unwrap();
    fast.finish_sync(|_| unreachable!()).unwrap();
    assert_eq!(
        slow.publish_game(1, frame(json!({"sequence":1}))),
        Err(OutputError::SlowConsumer)
    );
    fast.publish_game(1, frame(json!({"sequence":1}))).unwrap();
    let close = slow_receiver.close.borrow().clone().unwrap();
    assert_eq!(close.code, Some(1013));
    assert_eq!(close.reason, "slow consumer");
    assert_eq!(slow.close_reason().as_deref(), Some("slow_consumer"));
    assert!(fast.is_alive());
    assert_eq!(drain(&mut fast_receiver).len(), 2);
    assert_eq!(drain(&mut slow_receiver).len(), 1);
    slow.service_restart();
    assert_eq!(
        slow_receiver.close.borrow().as_ref().unwrap().code,
        Some(1013)
    );
}

