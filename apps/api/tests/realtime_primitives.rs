#[test]
fn cursor_binds_room_generation_direction_and_original_bytes() {
    let codec = ChatCursorCodec::new("test-secret");
    let cursor = codec.encode("room", 123, 42, Direction::After);
    assert!(
        codec
            .decode(&cursor, "other", 123, Direction::After)
            .is_err()
    );
    assert!(
        codec
            .decode(&cursor, "room", 124, Direction::After)
            .is_err()
    );
    assert!(
        codec
            .decode(&cursor, "room", 123, Direction::Before)
            .is_err()
    );
    assert!(
        ChatCursorCodec::new("other-secret")
            .decode(&cursor, "room", 123, Direction::After)
            .is_err()
    );
    for invalid in [
        "".to_owned(),
        format!("{cursor}.extra"),
        format!("{cursor}x"),
        format!("{cursor}="),
    ] {
        assert!(
            codec
                .decode(&invalid, "room", 123, Direction::After)
                .is_err()
        );
    }
    let sign = |raw: &str| {
        let encoded = URL_SAFE_NO_PAD.encode(raw);
        let mut mac = Hmac::<Sha256>::new_from_slice(b"test-secret").unwrap();
        mac.update(format!("multi-chat-cursor-v1:{encoded}").as_bytes());
        format!(
            "{encoded}.{}",
            URL_SAFE_NO_PAD.encode(mac.finalize().into_bytes())
        )
    };
    // A reordered/whitespace payload is still authenticated over its exact bytes.
    assert_eq!(
        codec.decode(
            &sign(r#"{ "g":123, "d":"after", "p":42,"r":"room", "v":1 }"#),
            "room",
            123,
            Direction::After
        ),
        Ok(42)
    );
    for raw in [
        r#"{"v":1,"r":"room","p":-1,"d":"after","g":123}"#,
        r#"{"v":2,"r":"room","p":42,"d":"after","g":123}"#,
        r#"{"v":1,"r":"room","p":42,"d":"after","g":123,"extra":0}"#,
        r#"{"v":1,"r":"room","p":42,"d":"after","g":123}{}"#,
    ] {
        assert!(
            codec
                .decode(&sign(raw), "room", 123, Direction::After)
                .is_err()
        );
    }
}

#[tokio::test]
async fn barrier_deduplicates_overlap_and_separates_game_chat_watermarks() {
    let (output, mut receiver) = ConnectionOutput::new(64, 5, Some(10)).unwrap();
    output
        .send_control(ServerControl::HelloOk {
            room_id: "room".into(),
            target_game_sequence: 7,
            target_chat_cursor: Some("chat:12".into()),
        })
        .unwrap();
    for sequence in [8, 7, 6] {
        output
            .publish_game(
                sequence,
                frame(json!({"type":"room.cursor","sequence":sequence})),
            )
            .unwrap();
    }
    output
        .publish_chat(
            13,
            Some(frame(json!({"type":"chat.message","cursor":"chat:13"}))),
        )
        .unwrap();
    output.publish_chat(12, None).unwrap();
    output
        .publish_chat(
            11,
            Some(frame(json!({"type":"chat.message","cursor":"chat:11"}))),
        )
        .unwrap();
    for sequence in [6, 7] {
        output
            .replay_game(
                sequence,
                frame(json!({"type":"room.cursor","sequence":sequence})),
            )
            .unwrap();
    }
    output
        .replay_chat(
            11,
            Some(frame(json!({"type":"chat.message","cursor":"chat:11"}))),
        )
        .await
        .unwrap();
    output.replay_chat(12, None).await.unwrap();
    let watermarks = output
        .finish_sync(|position| format!("chat:{position}"))
        .unwrap();
    assert_eq!(
        (watermarks.game_sequence, watermarks.chat_position),
        (8, Some(13))
    );
    output
        .publish_game(9, frame(json!({"type":"room.cursor","sequence":9})))
        .unwrap();
    output.publish_chat(14, None).unwrap();
    assert_eq!(output.watermarks().chat_position, Some(14));
    let messages = drain(&mut receiver);
    let game: Vec<_> = messages
        .iter()
        .filter_map(|message| message.get("sequence").and_then(Value::as_i64))
        .collect();
    assert_eq!(game, vec![6, 7, 8, 9]);
    let chats: Vec<_> = messages
        .iter()
        .filter_map(|message| message.get("cursor").and_then(Value::as_str))
        .collect();
    assert_eq!(chats, vec!["chat:11", "chat:13"]);
    let completion = messages
        .iter()
        .position(|message| message["type"] == "sync.complete")
        .unwrap();
    assert_eq!(
        messages[completion],
        json!({"type":"sync.complete","gameSequence":8,"chatCursor":"chat:13"})
    );
    assert_eq!(messages[completion + 1]["sequence"], 9);
}

