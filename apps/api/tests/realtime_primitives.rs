#[test]
fn replacement_is_fifo_and_stale_cleanup_cannot_unregister_new_generation() {
    let registry = ConnectionRegistry::default();
    let (old, mut old_receiver) = ConnectionOutput::new(4, 0, None).unwrap();
    old.finish_sync(|_| unreachable!()).unwrap();
    old.publish_game(1, frame(json!({"sequence":1}))).unwrap();
    let first = registry.register("r".into(), "m".into(), old.clone());
    let (new, _) = ConnectionOutput::new(4, 1, None).unwrap();
    let second = registry.register("r".into(), "m".into(), new.clone());
    assert!(!registry.unregister(&first));
    assert_eq!(
        registry.current("r", "m").unwrap().generation,
        second.generation
    );
    assert_eq!(
        old.publish_game(2, frame(json!({"sequence":2}))),
        Err(OutputError::Closed)
    );
    assert_eq!(
        old_receiver.frames.try_recv().unwrap().text.as_ref(),
        r#"{"type":"sync.complete","gameSequence":0}"#
    );
    assert_eq!(
        old_receiver.frames.try_recv().unwrap().text.as_ref(),
        r#"{"sequence":1}"#
    );
    let replacement = old_receiver.frames.try_recv().unwrap();
    assert!(replacement.close_after);
    assert_eq!(
        serde_json::from_str::<Value>(&replacement.text).unwrap(),
        json!({"type":"replaced","reason":"replaced"})
    );
    assert!(
        old_receiver.close.borrow().is_none(),
        "writer must drain FIFO before closing"
    );
    old.mark_closed();
    assert_eq!(old.close_reason().as_deref(), Some("replaced"));
    assert!(registry.unregister(&second));
    assert!(registry.current("r", "m").is_none());
}

