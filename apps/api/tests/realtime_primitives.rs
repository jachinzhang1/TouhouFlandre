fn frame(value: Value) -> Arc<str> {
    value.to_string().into()
}

fn drain(receiver: &mut OutboundReceiver) -> Vec<Value> {
    let mut frames = Vec::new();
    while let Ok(message) = receiver.frames.try_recv() {
        frames.push(serde_json::from_str(&message.text).unwrap());
    }
    frames
}

#[test]
fn strict_hello_preserves_game_only_and_rejection_semantics() {
    let hello = decode_hello(
        br#"{"type":"hello","token":"secret","lastGameSequence":0}"#,
        4096,
    )
    .unwrap();
    assert_eq!(hello.token, "secret");
    assert_eq!(hello.last_game_sequence, 0);
    assert_eq!(hello.last_chat_cursor, None);
    let subscribed = decode_hello(
        br#"{"type":"hello","token":"secret","lastGameSequence":-1,"lastChatCursor":"cursor"}"#,
        4096,
    )
    .unwrap();
    assert_eq!(subscribed.last_game_sequence, -1);
    assert_eq!(subscribed.last_chat_cursor.as_deref(), Some("cursor"));
    for invalid in [
        r#"{"type":"ack","token":"secret","lastGameSequence":0}"#,
        r#"{"type":"hello","token":"","lastGameSequence":0}"#,
        r#"{"type":"hello","token":"secret"}"#,
        r#"{"type":"hello","token":"secret","lastGameSequence":null}"#,
        r#"{"type":"hello","token":"secret","lastGameSequence":0.5}"#,
        r#"{"type":"hello","token":"secret","lastGameSequence":0,"unknown":1}"#,
        r#"{"type":"hello","token":"secret","lastGameSequence":0}{}"#,
    ] {
        assert_eq!(
            decode_hello(invalid.as_bytes(), 4096),
            Err(HelloError::Invalid),
            "{invalid}"
        );
    }
    assert_eq!(decode_hello(b"{}", 1), Err(HelloError::TooLarge));
}

