//! Run explicitly with TEST_DATABASE_URL pointing at disposable local Postgres:
//! cargo test --test database_migrations -- --include-ignored
use anyhow::Result;
use sqlx::{
    Connection, Executor, PgConnection, PgPool,
    migrate::Migrate,
    postgres::{PgConnectOptions, PgPoolOptions},
};
use std::str::FromStr;
use touhouflandre_api::database::{self, LegacyAdoption, MIGRATOR};

struct TestDatabase {
    admin: PgConnection,
    pool: PgPool,
    name: String,
}
impl TestDatabase {
    async fn new() -> Result<Self> {
        let url = std::env::var("TEST_DATABASE_URL")
            .expect("TEST_DATABASE_URL must name a disposable local PostgreSQL server");
        let options = PgConnectOptions::from_str(&url)?;
        let mut admin = PgConnection::connect_with(&options).await?;
        let name = format!("rust_migration_{}", uuid::Uuid::new_v4().simple());
        // Identifier is generated exclusively from a fixed prefix and UUID hex.
        admin
            .execute(sqlx::AssertSqlSafe(format!("CREATE DATABASE {name}")))
            .await?;
        let pool = PgPoolOptions::new()
            .max_connections(4)
            .connect_with(options.database(&name))
            .await?;
        Ok(Self { admin, pool, name })
    }
    async fn close(mut self) -> Result<()> {
        self.pool.close().await;
        self.admin
            .execute(sqlx::AssertSqlSafe(format!("DROP DATABASE {}", self.name)))
            .await?;
        self.admin.close().await?;
        Ok(())
    }
}

#[test]
fn converted_migrations_preserve_all_baseline_sql() {
    use sha2::Digest;
    use sha2::Sha256;
    let baseline: serde_json::Value = serde_json::from_str(include_str!(
        "../../../docs/rust-backend-migration/migration-baseline.json"
    ))
    .unwrap();
    let records = baseline["migrations"].as_array().unwrap();
    assert_eq!(records.len(), 23);
    assert_eq!(MIGRATOR.iter().count(), 46);
    for record in records {
        let version = record["version"].as_i64().unwrap();
        for direction in ["up", "down"] {
            let migration = MIGRATOR
                .iter()
                .find(|m| {
                    m.version == version
                        && m.migration_type.is_up_migration() == (direction == "up")
                })
                .unwrap();
            let checksum = Sha256::digest(migration.sql.as_ref().as_bytes())
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect::<String>();
            assert_eq!(
                checksum,
                record[format!("{direction}_sha256")],
                "version {version} {direction}"
            );
            assert!(!migration.sql.as_ref().contains("-- +goose"));
        }
    }
}

#[tokio::test]
#[ignore = "requires explicitly isolated TEST_DATABASE_URL"]
async fn fresh_migrate_repeat_and_reverse() -> Result<()> {
    let db = TestDatabase::new().await?;
    database::migrate(&db.pool, LegacyAdoption::Refuse).await?;
    database::migrate(&db.pool, LegacyAdoption::Refuse).await?;
    let versions: i64 = sqlx::query_scalar("SELECT count(*) FROM _sqlx_migrations WHERE success")
        .fetch_one(&db.pool)
        .await?;
    assert_eq!(versions, 23);
    let infinity: bool = sqlx::query_scalar("SELECT 'infinity'::timestamptz > now()")
        .fetch_one(&db.pool)
        .await?;
    assert!(infinity);
    // The baseline's roster migrations intentionally have no-op Down scripts:
    // production rollback retains expanded schema. Test the reversible tail,
    // not an unsupported destructive rollback all the way to version zero.
    MIGRATOR.undo(&db.pool, 21).await?;
    let removed: bool = sqlx::query_scalar("SELECT to_regclass('public.puzzle_resolve_idempotency') IS NULL AND to_regclass('public.game_session') IS NOT NULL").fetch_one(&db.pool).await?;
    assert!(removed);
    database::migrate(&db.pool, LegacyAdoption::Refuse).await?;
    db.close().await
}

async fn legacy_schema(pool: &PgPool, through: i64) -> Result<()> {
    sqlx::raw_sql("CREATE TABLE goose_db_version (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now()); INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)").execute(pool).await?;
    for migration in MIGRATOR
        .iter()
        .filter(|m| m.migration_type.is_up_migration() && m.version <= through)
    {
        let mut tx = pool.begin().await?;
        // Converted SQL is independently hashed against the unmodified Goose
        // baseline above. Execute one version per transaction as Goose did.
        sqlx::raw_sql(sqlx::AssertSqlSafe(migration.sql.as_ref()))
            .execute(&mut *tx)
            .await?;
        sqlx::query("INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)")
            .bind(migration.version)
            .execute(&mut *tx)
            .await?;
        tx.commit().await?;
    }
    Ok(())
}

#[tokio::test]
#[ignore = "requires explicitly isolated TEST_DATABASE_URL"]
async fn goose_adoption_preserves_data_and_applies_pending_only() -> Result<()> {
    let db = TestDatabase::new().await?;
    legacy_schema(&db.pool, 22).await?;
    sqlx::query("INSERT INTO work(id,title_zh,title_ja,short_name,type,release_year) VALUES ('legacy-sentinel','旧数据','旧データ','旧','game',2000)").execute(&db.pool).await?;
    assert!(
        database::migrate(&db.pool, LegacyAdoption::Refuse)
            .await
            .is_err()
    );
    let untouched: bool =
        sqlx::query_scalar("SELECT to_regclass('public._sqlx_migrations') IS NULL")
            .fetch_one(&db.pool)
            .await?;
    assert!(untouched);
    database::migrate(&db.pool, LegacyAdoption::AdoptGoose).await?;
    database::migrate(&db.pool, LegacyAdoption::AdoptGoose).await?;
    database::migrate(&db.pool, LegacyAdoption::Refuse).await?;
    let title: String = sqlx::query_scalar("SELECT title_zh FROM work WHERE id='legacy-sentinel'")
        .fetch_one(&db.pool)
        .await?;
    assert_eq!(title, "旧数据");
    let versions: i64 = sqlx::query_scalar("SELECT count(*) FROM _sqlx_migrations WHERE success")
        .fetch_one(&db.pool)
        .await?;
    assert_eq!(versions, 23);
    let pending_applied: bool =
        sqlx::query_scalar("SELECT to_regclass('public.puzzle_resolve_idempotency') IS NOT NULL")
            .fetch_one(&db.pool)
            .await?;
    assert!(pending_applied);
    MIGRATOR.undo(&db.pool, 21).await?;
    database::migrate(&db.pool, LegacyAdoption::Refuse).await?;
    let restored: i64 = sqlx::query_scalar("SELECT count(*) FROM _sqlx_migrations WHERE success")
        .fetch_one(&db.pool)
        .await?;
    assert_eq!(
        restored, 23,
        "SQLx rollback must not revive stale Goose authority"
    );
    sqlx::query("UPDATE _sqlx_migrations SET checksum = decode('00', 'hex') WHERE version=1")
        .execute(&db.pool)
        .await?;
    assert!(
        database::migrate(&db.pool, LegacyAdoption::Refuse)
            .await
            .is_err(),
        "changed SQL checksum must fail"
    );
    db.close().await
}

#[tokio::test]
#[ignore = "requires explicitly isolated TEST_DATABASE_URL"]
async fn interrupted_adoption_rolls_back_and_can_retry() -> Result<()> {
    let db = TestDatabase::new().await?;
    legacy_schema(&db.pool, 3).await?;
    let mut connection = db.pool.acquire().await?;
    connection
        .ensure_migrations_table("_sqlx_migrations")
        .await?;
    drop(connection);
    sqlx::raw_sql("CREATE FUNCTION fail_second_adoption() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.version = 2 THEN RAISE EXCEPTION 'injected adoption failure'; END IF; RETURN NEW; END $$; CREATE TRIGGER fail_second_adoption BEFORE INSERT ON _sqlx_migrations FOR EACH ROW EXECUTE FUNCTION fail_second_adoption()")
        .execute(&db.pool).await?;
    assert!(
        database::migrate(&db.pool, LegacyAdoption::AdoptGoose)
            .await
            .is_err()
    );
    let count: i64 = sqlx::query_scalar("SELECT count(*) FROM _sqlx_migrations")
        .fetch_one(&db.pool)
        .await?;
    assert_eq!(count, 0, "first inserted version must also roll back");
    let marker_absent: bool = sqlx::query_scalar(
        "SELECT to_regclass('public._touhouflandre_migration_adoption') IS NULL",
    )
    .fetch_one(&db.pool)
    .await?;
    assert!(marker_absent);
    sqlx::raw_sql("DROP TRIGGER fail_second_adoption ON _sqlx_migrations; DROP FUNCTION fail_second_adoption()")
        .execute(&db.pool).await?;
    database::migrate(&db.pool, LegacyAdoption::AdoptGoose).await?;
    database::migrate(&db.pool, LegacyAdoption::Refuse).await?;
    db.close().await
}

#[tokio::test]
#[ignore = "requires explicitly isolated TEST_DATABASE_URL"]
async fn empty_goose_ledger_adopts_and_concurrent_adoption_is_repeatable() -> Result<()> {
    let db = TestDatabase::new().await?;
    legacy_schema(&db.pool, 0).await?;
    let (first, second) = tokio::join!(
        database::migrate(&db.pool, LegacyAdoption::AdoptGoose),
        database::migrate(&db.pool, LegacyAdoption::AdoptGoose)
    );
    first?;
    second?;
    let adopted_version: i64 = sqlx::query_scalar(
        "SELECT goose_version FROM _touhouflandre_migration_adoption WHERE singleton",
    )
    .fetch_one(&db.pool)
    .await?;
    assert_eq!(adopted_version, 0);
    let versions: i64 = sqlx::query_scalar("SELECT count(*) FROM _sqlx_migrations WHERE success")
        .fetch_one(&db.pool)
        .await?;
    assert_eq!(versions, 23);
    sqlx::query("DROP TABLE _sqlx_migrations")
        .execute(&db.pool)
        .await?;
    assert!(
        database::migrate(&db.pool, LegacyAdoption::AdoptGoose)
            .await
            .is_err()
    );
    db.close().await
}

